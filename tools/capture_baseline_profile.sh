#!/usr/bin/env bash
# Captures Mochibun's real ART usage profile from a rooted device and turns it into
# app/src/main/baseline-prof.txt. Libraries (Compose, Coil, ...) ship their own profiles,
# so only Mochibun's own classes are kept.
#
# Usage: install a *debug* build (unminified names), use the launcher normally for a while,
# then run this from the repo root:  tools/capture_baseline_profile.sh
set -euo pipefail

PKG=com.crinklecodone.mochibun
OUT=app/src/main/baseline-prof.txt
TMP=$(mktemp)
trap 'rm -f "$TMP"' EXIT

APK=$(adb shell pm path "$PKG" | sed 's/^package://' | tr -d '\r')
[ -n "$APK" ] || { echo "$PKG is not installed" >&2; exit 1; }

adb shell su -c "'profman --profile-file=/data/misc/profiles/cur/0/$PKG/primary.prof \
    --apk=$APK --dex-location=$APK --dump-classes-and-methods'" | tr -d '\r' > "$TMP"

{
    echo "# Mochibun Baseline Profile"
    echo "# Generated by tools/capture_baseline_profile.sh from real on-device usage."
    echo "# Compiler-numbered lambda/synthetic classes are collapsed to wildcards so rules survive code changes."
    echo
    grep -E '^[HSP]*Lcom/(crinklecodone/mochibun|android/quickstep)/' "$TMP" | awk '
        {
            match($0, /^[HSP]*/); flags = substr($0, 1, RLENGTH); rule = substr($0, RLENGTH + 1)
            cls = rule; sub(/;.*/, "", cls)
            # Numbered lambdas/synthetics change between builds: match all nested classes of the outer class
            if (cls ~ /\$/ && (cls ~ /ExternalSynthetic|\$lambda|\$[0-9]+(\$|$)|ComposableSingletons/)) {
                outer = cls; sub(/\$.*/, "", outer)
                rule = (rule ~ /->/) ? outer "$**;->**(**)**" : outer "$**;"
            }
            if (!(rule in seen)) { order[++n] = rule; seen[rule] = "" }
            for (i = 1; i <= length(flags); i++) {
                c = substr(flags, i, 1)
                if (index(seen[rule], c) == 0) seen[rule] = seen[rule] c
            }
        }
        END {
            for (i = 1; i <= n; i++) {
                r = order[i]; f = ""
                # Canonical H, S, P order
                if (index(seen[r], "H")) f = f "H"
                if (index(seen[r], "S")) f = f "S"
                if (index(seen[r], "P")) f = f "P"
                print f r
            }
        }' | sort -u
} > "$OUT"

echo "Wrote $(grep -vc '^#\|^$' "$OUT") rules to $OUT"
